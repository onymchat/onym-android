package app.onym.android.mesh

import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.int
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive
import kotlinx.serialization.json.long
import org.junit.Assert.assertArrayEquals
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * Coded frames (onym-ios docs/mesh-ble-v1.md §4c) against the shared
 * vectors' "coded" section — generated by a Python implementation
 * independent of both apps. onym-ios checks the same file.
 */
class MeshCodingTest {
    private val v: JsonObject = Json.parseToJsonElement(
        javaClass.classLoader!!.getResource("mesh-v1-vectors.json")!!.readText(),
    ).jsonObject
    private val coded = v.getValue("coded").jsonObject

    private fun str(key: String) = coded.getValue(key).jsonPrimitive.content

    @Test fun coefficientsMatchTheVectors() {
        val c = coded.getValue("coefficients").jsonObject
        val values = MeshFountain.coefficients(
            envelopeId = c.getValue("envelopeID").jsonPrimitive.content.toInt(16),
            index = c.getValue("index").jsonPrimitive.int,
            k = c.getValue("k").jsonPrimitive.int,
        )
        assertEquals(c.getValue("values").jsonArray.map { it.jsonPrimitive.int }, values.toList())
    }

    @Test fun encoderFramesMatchTheVectors() {
        val envelope = str("envelopeHex").hexToBytes()
        val envelopeId = str("envelopeID").toInt(16)
        val encoder = MeshFountain.Encoder.of(envelope, envelopeId)!!
        assertEquals(coded.getValue("k").jsonPrimitive.int, encoder.k)
        val epoch = v.getValue("epoch").jsonPrimitive.long
        val tag = MeshTag.fromBytes(v.getValue("tags").jsonArray[0].jsonObject.getValue("tag").jsonPrimitive.content.hexToBytes(), 0)
        val frames = coded.getValue("frames").jsonArray.indices.map { i ->
            MeshCodedFrame((epoch and 0xFF).toInt(), tag, envelopeId, encoder.k, i, encoder.symbol(i)).encode().toHex()
        }
        assertEquals(coded.getValue("frames").jsonArray.map { it.jsonPrimitive.content }, frames)
    }

    /** Any k independent frames: only repair frames from the vectors, reversed. */
    @Test fun decodesFromRepairFramesAlone() {
        val frames = coded.getValue("frames").jsonArray.map { MeshCodedFrame.decode(it.jsonPrimitive.content.hexToBytes())!! }
        val k = coded.getValue("k").jsonPrimitive.int
        val decoder = MeshFountain.Decoder(k, frames[0].envelopeId)
        var out: ByteArray? = null
        for (f in frames.filter { it.index >= k }.reversed()) out = decoder.add(f.index, f.symbol) ?: out
        assertArrayEquals(str("envelopeHex").hexToBytes(), out)
    }

    @Test fun anyKFramesInAnyOrderDecode() {
        val envelope = ByteArray(500) { (it * 37).toByte() }
        val encoder = MeshFountain.Encoder.of(envelope, 0x1234)!!
        var failures = 0
        repeat(50) {
            val indices = (0 until encoder.k * 2).shuffled().take(encoder.k + 1)
            val decoder = MeshFountain.Decoder(encoder.k, 0x1234)
            var out: ByteArray? = null
            for (i in indices) out = decoder.add(i, encoder.symbol(i)) ?: out
            if (!envelope.contentEquals(out)) failures++
        }
        assertTrue("k+1 random frames should almost always decode ($failures failures)", failures <= 1)
    }

    @Test fun envelopeBinaryRoundTripsWithTheVectors() {
        val json = coded.getValue("sealedEnvelopeJSON").toString().encodeToByteArray()
        val binary = MeshEnvelope.binaryFromJson(json)!!
        assertEquals(str("sealedEnvelopeBinaryHex"), binary.toHex())
        val back = Json.parseToJsonElement(MeshEnvelope.jsonFromBinary(binary)!!.decodeToString()).jsonObject
        assertEquals(coded.getValue("sealedEnvelopeJSON").jsonObject, back)
    }

    @Test fun envelopeRejectsWhatIsntOne() {
        assertNull(MeshEnvelope.binaryFromJson("{}".encodeToByteArray()))
        assertNull(MeshEnvelope.jsonFromBinary(byteArrayOf(1, 2, 3)))
        assertNull(MeshEnvelope.jsonFromBinary(byteArrayOf(2) + ByteArray(200)))
    }

    /** Python's raw DEFLATE inflates here — the wire contract, not this
     *  implementation's own output. */
    @Test fun payloadExpandsAnIndependentlyDeflatedPayload() {
        assertArrayEquals(str("payloadHex").hexToBytes(), MeshPayload.expand(str("compressedPlaintextHex").hexToBytes()))
        val json = """{"a":1}""".encodeToByteArray()
        assertArrayEquals("unmarked plaintext passes through", json, MeshPayload.expand(json))
        val payload = str("payloadHex").hexToBytes()
        assertArrayEquals(payload, MeshPayload.expand(MeshPayload.compress(payload)))
        assertNull("garbage after the marker", MeshPayload.expand(byteArrayOf(1, -1, -1)))
    }
}
