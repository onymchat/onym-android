/**
 * The cross-platform contract. `mesh-v1-vectors.json` is copied from
 * onym-ios (`Packages/OnymMesh/Tests/OnymMeshTests/Fixtures/`), where it
 * was generated by an implementation separate from both apps. iOS checks
 * against the same file; a change here that isn't a deliberate protocol
 * version bump is a bug.
 */
class MeshVectorsTest {
    private val v: JsonObject = Json.parseToJsonElement(
        javaClass.classLoader!!.getResource("mesh-v1-vectors.json")!!.readText(),
    ).jsonObject

    private fun str(key: String) = v.getValue(key).jsonPrimitive.content
    private fun hex(key: String) = str(key).hexToBytes()

    @Test fun pairKeyIsTheSameFromEitherSide() {
        val alice = X25519PrivateKeyParameters(hex("alicePrivateKey"), 0)
        val bob = X25519PrivateKeyParameters(hex("bobPrivateKey"), 0)
        assertArrayEquals(hex("alicePublicKey"), alice.generatePublicKey().encoded)
        assertArrayEquals(hex("bobPublicKey"), bob.generatePublicKey().encoded)
        assertArrayEquals(hex("pairKey"), MeshPairKey.derive(alice, hex("bobPublicKey")))
        assertArrayEquals(hex("pairKey"), MeshPairKey.derive(bob, hex("alicePublicKey")))
    }

    @Test fun epochAndTags() {
        assertEquals(v.getValue("epoch").jsonPrimitive.long, MeshEpoch.number(Instant.parse(str("date"))))
        for (t in v.getValue("tags").jsonArray) {
            val epoch = t.jsonObject.getValue("epoch").jsonPrimitive.long
            val tag = t.jsonObject.getValue("tag").jsonPrimitive.content
            assertEquals("epoch $epoch", tag, MeshTag.toBytes(MeshTag.derive(hex("pairKey"), epoch)).toHex())
        }
    }

    @Test fun v1FramesEncodeAndReassemble() {
        val epoch = v.getValue("epoch").jsonPrimitive.long
        val frames = MeshFrameCodec.fragmentV1(
            envelope = hex("envelopeHex"),
            tag = MeshTag.derive(hex("pairKey"), epoch),
            epoch = epoch,
            envelopeId = str("envelopeID").toLong(16),
            maxFrameSize = v.getValue("maxFrameSize").jsonPrimitive.int,
        )!!
        assertEquals(v.getValue("frames").jsonArray.map { it.jsonPrimitive.content }, frames.map { it.toHex() })

        val r = MeshReassembler()
        val out = frames.reversed().mapNotNull { r.add(MeshFrameCodec.decodeV1(it)!!, Instant.now()) }
        assertEquals(listOf(str("envelopeHex")), out.map { it.toHex() })
    }

    @Test fun compactFramesEncodeResolveAndReassemble() {
        val epoch = v.getValue("epoch").jsonPrimitive.long
        val frames = MeshFrameCodec.fragmentCompact(
            envelope = hex("envelopeHex"),
            tag = MeshTag.derive(hex("pairKey"), epoch),
            epoch = epoch,
            envelopeId = str("compactEnvelopeID").toInt(16),
            maxChunk = v.getValue("compactMaxChunk").jsonPrimitive.int,
        )!!
        assertEquals(v.getValue("compactFrames").jsonArray.map { it.jsonPrimitive.content }, frames.map { it.toHex() })

        val r = MeshReassembler()
        val out = frames.mapNotNull { bytes ->
            val c = MeshFrameCodec.decodeCompact(bytes)!!
            val resolved = MeshFrameCodec.resolveEpoch(c.epochLow, oldest = epoch - 96, current = epoch)!!
            assertEquals(epoch, resolved)
            r.add(c.toFrame(resolved), Instant.now())
        }
        assertEquals(listOf(str("envelopeHex")), out.map { it.toHex() })
    }
}

internal fun String.hexToBytes(): ByteArray = ByteArray(length / 2) { i -> substring(2 * i, 2 * i + 2).toInt(16).toByte() }

internal fun ByteArray.toHex(): String = joinToString("") { "%02x".format(it) }
